package connpass

import (
	"testing"
	"time"
)

func jstTime(t *testing.T, s string) time.Time {
	t.Helper()
	v, err := time.ParseInLocation("2006-01-02 15:04", s, jst)
	if err != nil {
		t.Fatal(err)
	}
	return v
}

func TestInEventWindow(t *testing.T) {
	cases := []struct {
		name       string
		start, end string
		at         string
		want       bool
	}{
		// 1日のイベント 19:00〜21:00
		{"開始31分前は不可", "2026-11-28 19:00", "2026-11-28 21:00", "2026-11-28 18:29", false},
		{"開始30分前は可", "2026-11-28 19:00", "2026-11-28 21:00", "2026-11-28 18:30", true},
		{"開催中は可", "2026-11-28 19:00", "2026-11-28 21:00", "2026-11-28 20:00", true},
		{"終了30分後は可", "2026-11-28 19:00", "2026-11-28 21:00", "2026-11-28 21:30", true},
		{"終了31分後は不可", "2026-11-28 19:00", "2026-11-28 21:00", "2026-11-28 21:31", false},
		// 日付をまたぐ1日のイベント 22:00〜翌2:00
		{"深夜イベントの翌1時は可", "2026-11-28 22:00", "2026-11-29 02:00", "2026-11-29 01:00", true},

		// 複数日のイベント 9/19 10:00〜9/27 18:00 → 毎日 9:30〜18:30
		{"複数日: 初日の開始30分前は可", "2026-09-19 10:00", "2026-09-27 18:00", "2026-09-19 09:30", true},
		{"複数日: 中日の昼は可", "2026-09-19 10:00", "2026-09-27 18:00", "2026-09-23 13:00", true},
		{"複数日: 中日の夜は不可", "2026-09-19 10:00", "2026-09-27 18:00", "2026-09-23 22:00", false},
		{"複数日: 中日の早朝は不可", "2026-09-19 10:00", "2026-09-27 18:00", "2026-09-23 09:29", false},
		{"複数日: 最終日の終了30分後は可", "2026-09-19 10:00", "2026-09-27 18:00", "2026-09-27 18:30", true},
		{"複数日: 期間前日は不可", "2026-09-19 10:00", "2026-09-27 18:00", "2026-09-18 12:00", false},
		{"複数日: 期間翌日は不可", "2026-09-19 10:00", "2026-09-27 18:00", "2026-09-28 12:00", false},

		// 複数日で毎日夜〜翌朝 11/1 22:00〜11/4 02:00 → 毎日 21:30〜翌2:30
		{"複数日夜間: 深夜1時は可", "2026-11-01 22:00", "2026-11-04 02:00", "2026-11-03 01:00", true},
		{"複数日夜間: 昼は不可", "2026-11-01 22:00", "2026-11-04 02:00", "2026-11-02 12:00", false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := InEventWindow(jstTime(t, tc.start), jstTime(t, tc.end), jstTime(t, tc.at).UTC())
			if got != tc.want {
				t.Errorf("InEventWindow(%s, %s, %s) = %v, want %v", tc.start, tc.end, tc.at, got, tc.want)
			}
		})
	}
}
